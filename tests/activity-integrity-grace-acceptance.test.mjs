import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const base=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const code=fs.readFileSync(path.join(base,'tracker/activity-integrity.js'),'utf8');
let now=1_800_000_000_000,checks=0;
const clock=class extends Date {static now(){return now;}};
const store=new Map();
function helper(){const scope={window:{},Date:clock,sessionStorage:{getItem:k=>store.get(k)??null,setItem:(k,v)=>store.set(k,v),removeItem:k=>store.delete(k)},JSON,String,Number,Math,console};vm.runInNewContext(code,scope);return scope.window.TrinoTimeActivityIntegrity.create;}
const ok=(name,value)=>{assert.ok(value,name);console.log('PASS '+(++checks)+' '+name);};
const create=helper();
let a=create('coverage');
const opts=(visible,focused,hasTask=true)=>({visible,focused,hasTask,osAway:false});
const inputEvent={type:'input',isTrusted:true,target:{closest:s=>s.includes('input')?{}:null}};
const mouseEvent={type:'mousemove',isTrusted:true,target:{closest:()=>null}};
const fakePointer={type:'pointerdown',isTrusted:true,target:{closest:()=>null}};
const genuineButton={type:'pointerdown',isTrusted:true,target:{closest:s=>s.includes('button')?{}:null}};
const back=opts(true,true),off=opts(true,false);
a.sync(true,true,'JOB_A|1','shift-a|1');
ok('real task starts with work evidence',a.state('active',back)==='active');
now+=1200;
ok('off-tool Discord switch gets 30s transition grace',a.state('active',off)==='grace');
now+=29_000;
ok('still grace before 30s boundary',a.state('active',off)==='grace');
now+=1000;
ok('exactly 30s becomes UNVERIFIED, not AWAY',a.state('active',off)==='unverified');
ok('OS active does not become AWAY due to second monitor',a.state('active',off)!=='away');
now+=25_000;
ok('mouse movement cannot reset 30s allowance',a.record(mouseEvent,true,true)===false&&a.state('active',off)==='unverified');
ok('blank-space pointer does not verify actual task work',!a.record(fakePointer,true,true));
now+=1000;
ok('focus alone cannot renew exhausted allowance',a.state('active',back)==='active'&&a.allowanceRemaining()===0);
ok('switching back to Discord without workflow action remains unverified',a.state('active',off)==='unverified');
now+=500;
ok('real task input renews allowance',a.record(inputEvent,true,true)===true&&a.state('active',off)==='grace');
now+=10_000;
a.state('active',back);
now+=5_000;
ok('cumulative allowance protects against repeated tab toggles',a.state('active',off)==='grace'&&a.allowanceRemaining()<=20_000);
now+=20_000;
ok('tab toggling cannot create unlimited 30s grants',a.state('active',off)==='unverified');
// Real on-tool action renews a new allocation. Restart still retains prior exhausted window.
let revived=create('coverage');
ok('tab reload retains same shift/activity allowance',revived.state('active',off)==='unverified');
revived.sync(true,true,'JOB_A|1','shift-a|1');
ok('same task does not automatically renew allowance',revived.state('active',off)==='unverified');
revived.record(genuineButton,true,true);
ok('trusted task control confirms workflow interaction',revived.state('active',off)==='grace');
now+=301_000;
ok('no on-tool progress for five minutes becomes unverified, not verified work',revived.state('active',back)==='unverified');
ok('locked computer remains AWAY',revived.state('active',{...back,osAway:true})==='away');
revived.sync(true,true,'JOB_A|2','shift-a|1');
ok('real next task gets fresh work evidence',revived.state('active',back)==='active');
revived.sync(true,true,'JOB_B|1','shift-b|1');
ok('shift-bound task evidence reinitializes on new shift',revived.state('active',back)==='active');
const conf=create('confirmation');conf.sync(true,true,'JOB_C|1','shift-c|1');
ok('Confirmation has own separate grace allowance',conf.state('active',off)==='grace');
ok('synthetic input never verifies work',!conf.record({...inputEvent,isTrusted:false},true,true));
const manifest=JSON.parse(fs.readFileSync(path.join(base,'tracker/manifest.json'),'utf8'));
ok('manifest injection loads integrity helper before either workflow',manifest.version==='2.2.63'&&manifest.content_scripts[0].js.indexOf('activity-integrity.js')<manifest.content_scripts[0].js.indexOf('coverage.js'));
for(const flow of ['coverage','confirmation']){
 const fg=fs.readFileSync(path.join(base,`tracker/${flow}.js`),'utf8');
 const bg=fs.readFileSync(path.join(base,`tracker/${flow}-background.js`),'utf8');
 ok(`${flow} logs GRACE and UNVERIFIED as their own buckets`,fg.includes('graceMs:')&&fg.includes('unverifiedMs:')&&bg.includes('s.graceMs=num(s.graceMs)+grace')&&bg.includes('s.unverifiedMs=num(s.unverifiedMs)+unverified'));
 ok(`${flow} does not upgrade mouse motion to task activity`,fg.includes('integrity?.record(event'));
}
const worker=fs.readFileSync(path.join(base,'cloudflare/src/worker.js'),'utf8');
ok('production Worker accepts both integrity statuses',worker.includes("'searching','grace','unverified','paused'"));
ok('production sanitizes new timing buckets',worker.includes('graceMs: coverageSafeMsServer(source.graceMs)')&&worker.includes('unverifiedMs: confirmationSafeMsServer(source.unverifiedMs)'));
console.log(`PASS activity-integrity 30-second grace: ${checks} synthetic checks`);
