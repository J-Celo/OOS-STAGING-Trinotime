import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const read=n=>fs.readFileSync(new URL('../tracker/'+n,import.meta.url),'utf8');
let checks=0;
const test=(name,condition)=>{assert.ok(condition,name);console.log('PASS '+(++checks)+' '+name);};
const store=new Map();
const tabs=new Map([[1,{url:'https://labeling-tools.augmoto.com/coverage'}],[2,{url:'https://labeling-tools.augmoto.com/confirmation'}]]);
const messages=[];
let now=100000;
const storage={get:async k=>({[k]:store.get(k)}),set:async obj=>{for(const [k,v] of Object.entries(obj))store.set(k,v);}};
const ownerVm={globalThis:{}};
vm.runInNewContext(read('activity-owner-core.js'),ownerVm);
const make=()=>ownerVm.globalThis.TrinoTimeActivityOwnerCore.create({storage,getTab:async id=>{if(!tabs.has(id))throw Error('closed');return tabs.get(id);},notify:async(old,msg)=>{messages.push([old.tabId,msg]);},now:()=>now});
let controller=make();
let a=await controller.request({tabId:1,workflow:'coverage',active:true,foreground:true});
test('Coverage receives first activity lease',a.owned===true);
now+=3000;
let b=await controller.request({tabId:2,workflow:'confirmation',active:true,foreground:true});
test('Confirmation takes shared lease',b.owned===true);
test('old Coverage tab is told to stop activity time',messages.at(-1)?.[0]===1&&messages.at(-1)?.[1]?.type==='tt-activity-owner-lost');
a=await controller.request({tabId:1,workflow:'coverage',active:true,foreground:false});
test('unfocused Coverage cannot take lease back',a.owned===false);
controller=make();
b=await controller.request({tabId:2,workflow:'confirmation',active:true,foreground:false});
test('owner survives service worker restart',b.owned===true);
await controller.releaseTab(2);
test('closing active tab releases lease',controller.current()===null);
a=await controller.request({tabId:1,workflow:'coverage',active:true,foreground:true});
test('Coverage may resume after release',a.owned===true);
const ac=read('availability-core.js');
test('reconnect uses existing auth-bound sync',ac.includes('core?.bridge?.token')&&ac.includes('core?.bridge?.deviceId')&&ac.includes('refreshShift()')&&ac.includes('sync()'));
const cb=read('confirmation.js'),cv=read('coverage.js');
test('Confirmation throttles mutation scans',cb.includes('let scanWake=null, lastMutationScanAt=0')&&cb.includes('if(scanWake!==null)return'));
test('Coverage avoids hidden-tab scans unless receipts need verification',cv.includes('document.hidden || confirmationRoute()')&&cv.includes('!submitPending() && !coverageBacklog.length'));
test('Submit listeners remain independent of activity ownership',cb.includes('captureExplicitConfirmationSubmit')&&cv.includes('function confirmPendingSubmit('));
const m=JSON.parse(read('manifest.json'));
test('staging identity and version intact',m.version==='2.2.63'&&m.name.includes('STAGING'));
test('all content scripts inject required coordinator',m.content_scripts[0].js.includes('workflow-coordinator.js'));
console.log('PASS staging owner / lightweight scan / reconnect: '+checks+' focused offline checks');
