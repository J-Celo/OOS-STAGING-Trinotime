import assert from 'node:assert/strict';
import fs from 'node:fs';
import {createHash} from 'node:crypto';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const meta=JSON.parse(read('public/downloads/qc-tracker.json'));
const tracker=JSON.parse(read('../tracker/manifest.json'));
const client=read('public/assets/js/j-tracker-download-rc33.js');
const worker=read('src/worker.js');
const fingerprint='TT-2.0.5-M2.9.52-EXCEL-CHART-COMPAT-PRODUCTION-20261009';
assert.equal(meta.environment,'PRODUCTION');
assert.equal(meta.version,'2.2.33');
assert.equal(tracker.version,meta.version);
assert.equal(tracker.name,'TrinoTime QC Tracker');
assert.deepEqual(tracker.host_permissions,['https://labeling-tools.augmoto.com/*','https://oos.trinotime.com/*']);
assert(client.includes("TRACKER_ENV = 'PRODUCTION'"));
assert(!client.includes('>STG<'));
assert(worker.includes(fingerprint));
assert(worker.includes("qc-tracker-v2.2.33-production"));
const bytes=fs.readFileSync(path.join(root,'public/downloads',meta.filename));
assert.equal(createHash('sha256').update(bytes).digest('hex'),meta.sha256);
const forbiddenHost='oostrinotime-staging-qa.trinoadmin.workers.dev';
for(const file of ['../tracker/coverage-background.js','../tracker/confirmation-background.js','../tracker/manifest.json','public/index.html','src/worker.js','public/assets/js/j-tracker-download-rc33.js']) assert(!read(file).includes(forbiddenHost),`${file} contains staging endpoint`);
for(const file of ['../tracker/coverage-background.js','../tracker/confirmation-background.js']) assert(read(file).includes('https://oos.trinotime.com'));
console.log('PASS — V2.0.5 production endpoint, UI, Tracker ZIP, metadata, and Worker packaging are coherent');
