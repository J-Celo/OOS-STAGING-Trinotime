import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
import {webcrypto} from 'node:crypto';
const root=new URL('../',import.meta.url);
const server=fs.readFileSync(new URL('src/worker.js',root),'utf8');
const metricUi=fs.readFileSync(new URL('public/assets/js/j-agent-metrics-rc22.js',root),'utf8');
const coverageUi=fs.readFileSync(new URL('public/assets/js/j-coverage-dashboard-rc20.js',root),'utf8');
const index=fs.readFileSync(new URL('public/index.html',root),'utf8');
const context=vm.createContext({URL,URLSearchParams,Request,Response,Headers,console,crypto:webcrypto,TextEncoder,TextDecoder,btoa,atob,createRemoteJWKSet:()=>({})});
vm.runInContext(server.replace(/^import .*;\n/gm,'').replace('export default {','const workerDefault = {').replace('export class ChatRealtimeHub','class ChatRealtimeHub')+`
globalThis.scoring={row:qcMetricRowServer,summary:qcMetricSummaryServer,cap:qcMetricCapPercentServer,shifts:qcMetricsShiftsServer,shiftKey:coverageActorKeyServer,encode:fbEncodeKeyServer};
`,context);
const t=context.scoring;
const agent={name:'Agent One',pod:'pod1'},target={secondsPerTask:10};
const fast=t.row(agent,'coverage',{submitted:1,efficiencyTaskCount:1,efficiencyActiveMs:5000},target,'POD 1');
const slow=t.row(agent,'confirmation',{submitted:1,efficiencyTaskCount:1,efficiencyActiveMs:50000},target,'POD 1');
assert.equal(fast.efficiencyPercent,100,'200% calculated efficiency displays 100%');
assert.equal(slow.efficiencyPercent,20);
assert.equal(fast.secondsPerTask,5,'original measured pace is not modified');
assert.equal(fast.measuredTasks,1,'actual task count is not modified');
assert.equal(t.cap(200),100);assert.equal(t.cap(150),100);assert.equal(t.cap(-2),0);assert.equal(t.cap(null),null);assert.equal(t.cap(Infinity),null);
const score=t.summary([fast,slow]);
assert(score.efficiency<=100&&score.efficiency>=0);
assert(Math.abs(score.efficiency-(15000/55000*100))<1e-9,'each workflow earned time capped before active-time weighted average');
assert.equal(score.totalMeasured,2);
assert.equal(t.summary([fast]).efficiency,100);
assert.equal(t.summary([{...slow,efficiencyPercent:null}]).efficiency,null,'missing grade does not become zero');
assert.equal(t.summary([{...fast,efficiencyPercent:200}]).efficiency,100,'older legacy record cannot inflate overall score');
const capUi=metricUi.slice(metricUi.indexOf('function gradeFor('),metricUi.indexOf('function duration('));
const summarize=vm.runInNewContext(`(function(){${capUi};return {summarize,capScore}})()`);
const frontScore=summarize.summarize([fast,slow]);
assert(Math.abs(frontScore.efficiency-score.efficiency)<1e-9,'frontend fallback matches server aggregate');
assert.equal(summarize.capScore(200),100);
assert.equal(summarize.capScore(null),null);
const coverageFn=coverageUi.slice(coverageUi.indexOf('function performanceView('),coverageUi.indexOf('function statusLabel('));
const coverage=vm.runInNewContext(`(function(){const DAILY_SUBMIT_TARGET=300,ACTIVE_DAY_HOURS=8,submittedTotal=(row)=>row.submitted;${coverageFn};return performanceView;})()`);
assert.equal(coverage({submitted:600,activeMs:28800000}).progress,100,'Coverage 200% daily target capped');
assert.equal(coverage({submitted:450,activeMs:28800000}).progress,100,'Coverage 150% daily target capped');
assert.equal(coverage({submitted:150,activeMs:28800000}).progress,50);
assert.equal(coverage({submitted:600,activeMs:28800000}).submitted,600,'actual Coverage tasks preserved');
assert(metricUi.includes('number(capScore(r.efficiencyPercent))'), 'legacy roster percentage display capped');
assert(metricUi.includes('number(capScore(m.efficiency))'), 'POD comparison display capped');
assert(metricUi.includes('Math.round(capScore(summary.efficiency))'), 'scorecard display capped');
assert(server.includes('const displayShifts=shifts.map('), 'previously locked source rows normalized only for API response');
assert(index.includes('score-cap-m2953=1'), 'browser cache key bumped for both changed dashboards');
console.log('PASS M2.9.53: measured task source unchanged; 150/200/legacy percentage caps; per-workflow bounded weighted team/Agent score; Coverage 300-task progress cap; null-safe grades; UI & server consistency; cache bust');
