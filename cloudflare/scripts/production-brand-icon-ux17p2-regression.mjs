import assert from 'node:assert/strict';
import { readFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
const cloudflare = dirname(dirname(fileURLToPath(import.meta.url)));
const read = p => readFileSync(join(cloudflare, p),'utf8');
const js = read('public/assets/js/j-d91d2b3b0f5b.js');
const html = read('public/index.html');
const css = read('public/assets/css/c-brand-icon-ux17p2.css');
const img = join(cloudflare,'public/assets/img/trinotime-brand-mark-transparent.png');
assert(existsSync(img), 'use existing bundled TrinoTime brand asset');
const data=readFileSync(img);
assert.equal(data.subarray(1,4).toString('ascii'),'PNG');
assert.equal(data.readUInt32BE(16),192);
assert.equal(data.readUInt32BE(20),192);
assert.equal(data[25],6,'official mark must retain alpha for light/dark use');
assert.match(js,/const workspaceMark = \(size = 12\)/);
assert.equal((js.match(/\$\{workspaceMark\(12\)\}/g)||[]).length,1);
assert.equal((js.match(/\$\{workspaceMark\(8\)\}/g)||[]).length,1);
assert(!js.includes("icon('crown')"), 'no crown rendered in workspace badges');
assert.match(html,/c-brand-icon-ux17p2\.css\?v=3\.0\.4-ux17p2/);
assert.match(html,/c-brand-icon-ux17p2\.css/);
assert.match(css,/width: 12px !important/);
assert.match(css,/width: 14px !important/);
assert.match(css,/width: 8px !important/);
assert.match(css,/body\.dark-mode/);
assert.match(css,/filter: none !important/);
assert(!css.includes('display: none'), 'brand mark visible');
console.log('PASS UX17.2 official brand mark: existing PNG, two placements, exact sizes, both themes, cache bust.');
