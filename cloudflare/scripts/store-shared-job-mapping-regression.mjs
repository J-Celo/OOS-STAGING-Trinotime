import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import {webcrypto} from 'node:crypto';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const worker=fs.readFileSync(path.join(root,'src/worker.js'),'utf8');
const sandbox=vm.createContext({URL,Headers,Request,Response,console,crypto:webcrypto,TextEncoder,TextDecoder,btoa,atob,structuredClone,createRemoteJWKSet:()=>({})});
vm.runInContext(worker.replace(/^import .*;\n/gm,'').replace('export default {','const workerDefault = {').replace('export class ChatRealtimeHub','class ChatRealtimeHub')+`
requireWorkforceAttendanceActor=async req=>req.actor;
coverageVisibleAgentsServer=async(env,actor)=>({agents:actor.role==='admin'?env.agents:env.agents.filter(a=>a.pod===actor.pod)});
coverageActorKeyServer=(_role,name)=>name.toLowerCase();
firebaseAdminGet=async(env,loc)=>env.data[loc]||null;
globalThis.testReport=storeIntelReportServer;`,sandbox);
const date='2026-10-18';
const job=(name,pod,jobId,store,submitted)=>({name,pod,jobId,storeName:store,submitted,activeMs:submitted*1000,lastTask:4,totalTasks:4,status:'active'});
const agents=[{name:'Agent Alpha',pod:'pod-A'},{name:'Agent Beta',pod:'pod-A'},{name:'Agent Gamma',pod:'pod-A'},{name:'Agent Delta',pod:'pod-B'}];
const coverage={'agent alpha':{known:job('Agent Alpha','pod-A','JOB_11111','Chemist Store A',4),clash:job('Agent Alpha','pod-A','JOB_22222','Store B',3)},'agent beta':{shared:job('Agent Beta','pod-A','JOB_11111','',2),clash:job('Agent Beta','pod-A','JOB_22222','Store C',5),unmapped:job('Agent Beta','pod-A','JOB_33333','',1)},'agent gamma':{unmapped:job('Agent Gamma','pod-A','JOB_44444','',7)},'agent delta':{sameJobDifferentPod:job('Agent Delta','pod-B','JOB_44444','Other POD Store',20)}};
const confirmation={'agent beta':{differentWorkflow:job('Agent Beta','pod-A','JOB_11111','',6)}};
const env={agents,data:{[`workforceCoverage/v1/jobs/${date}`]:coverage,[`workforceConfirmation/v1/jobs/${date}`]:confirmation}};
const request={actor:{role:'team_leader',pod:'pod-A',name:'TL'},headers:new Headers()};
const report=await sandbox.testReport(request,env,new URL(`https://example.test/api/workforce/metrics/stores?date=${date}`),'metrics');
const lookup=(agent,id,workflow='coverage')=>report.jobs.find(j=>j.agent===agent&&j.jobId===id&&j.workflow===workflow);
const alpha=lookup('Agent Alpha','JOB_11111'),beta=lookup('Agent Beta','JOB_11111');
assert.equal(alpha.storeName,'Chemist Store A');assert.equal(alpha.mappingStatus,'observed');
assert.equal(beta.storeName,'Chemist Store A');assert.equal(beta.mappingStatus,'shared-job');
assert.equal(beta.submitted,2,'Shared-job mapping never merges Agent submissions');
assert.equal(lookup('Agent Beta','JOB_11111','confirmation').storeName,'Unknown Store','Never borrow across workflows');
assert.equal(lookup('Agent Gamma','JOB_44444').storeName,'Unknown Store','Never borrow from another POD');
assert.equal(lookup('Agent Beta','JOB_33333').storeName,'Unknown Store','Never invent missing name');
assert.equal(lookup('Agent Alpha','JOB_22222').mappingStatus,'conflict','Ambiguous store observations require review');
assert.equal(lookup('Agent Beta','JOB_22222').mappingStatus,'conflict','Conflict applies to all records of disputed shared job');
assert(!report.jobs.some(j=>j.agent==='Agent Delta'),'No other POD records in TL report');
assert.equal(report.jobs.reduce((sum,j)=>sum+j.submitted,0),28,'No change to confirmed submissions');
assert.equal(report.stores.reduce((sum,j)=>sum+j.submitted,0),28,'Aggregates agree with job ledger');
assert.equal(report.trends.reduce((sum,j)=>sum+j.submitted,0),28,'Trend totals agree');
assert.equal(report.sharedJobMapped,1);
console.log('PASS: shared Job ID corroboration; workflow, POD and Agent isolation; conflict quarantine; no inferred store without evidence; unchanged submission totals.');
